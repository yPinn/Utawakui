import { afterEach, expect, it, vi } from 'vitest';
import { createLyricsQuerySession } from './querySession.js';
import { createLyricsRequestBudget } from './requestPolicy.js';
afterEach(() => vi.useRealTimers());
it('charges shared physical work once per parent and never partially debits exhausted layers', () => {
  const root = createLyricsQuerySession({ maxAttempts: 2 });
  const stage = root.stage({ maxAttempts: 1, timeoutMs: 6000 });
  const a = createLyricsRequestBudget('lrclib', { parent: stage });
  const b = createLyricsRequestBudget('lrclib', { parent: stage });
  const token = {};
  a.consume(token);
  b.consume(token);
  expect(root.attempts).toBe(1);
  expect(stage.attempts).toBe(1);
  expect(() => a.consume({})).toThrow();
  expect(a.attempts).toBe(1);
  expect(root.attempts).toBe(1);
  const fallback = root.stage({ maxAttempts: 3, timeoutMs: 8000 });
  const c = createLyricsRequestBudget('kugou', { parent: fallback });
  c.consume({});
  expect(() => c.consume({})).toThrow();
  expect(c.attempts).toBe(1);
  expect(fallback.attempts).toBe(1);
  for (const item of [a, b, c, stage, fallback, root]) item.dispose();
});
it('keeps phase and provider deadlines below the original session deadline', async () => {
  vi.useFakeTimers();
  const root = createLyricsQuerySession({ timeoutMs: 20000 });
  await vi.advanceTimersByTimeAsync(19000);
  const stage = root.stage({ timeoutMs: 8000, maxAttempts: 5 });
  const child = createLyricsRequestBudget('kugou', { parent: stage });
  await vi.advanceTimersByTimeAsync(1000);
  expect(root.signal.aborted).toBe(true);
  expect(child.signal.aborted).toBe(true);
  expect(() => child.consume()).toThrow();
  child.dispose();
  stage.dispose();
  root.dispose();
});
